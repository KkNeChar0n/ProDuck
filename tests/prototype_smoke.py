"""Run against the standalone prototype server at localhost:4173."""
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

OUT = Path('docs/verification')
OUT.mkdir(parents=True, exist_ok=True)
with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    page = browser.new_page(viewport={"width":1440,"height":960})
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto('http://127.0.0.1:4173', wait_until='networkidle')
    expect(page.get_by_role('heading', name='优化客户筛选')).to_be_visible()
    page.screenshot(path=str(OUT/'workbench-desktop.png'), full_page=True)
    page.get_by_role('tab',name='文档',exact=True).click()
    expect(page.get_by_role('button',name='生成文档草稿',exact=True)).to_be_disabled()
    page.get_by_role('tab',name='原型',exact=True).click()
    page.get_by_label('搜索客户',exact=True).fill('不存在')
    page.get_by_role('button',name='搜索',exact=True).click()
    expect(page.get_by_text('没有匹配的客户，试试其他名称或重置筛选。')).to_be_visible()
    page.get_by_role('button',name='重置',exact=True).click()
    expect(page.get_by_text('共 4 位客户')).to_be_visible()
    page.get_by_role('button',name='＋ 新增客户',exact=True).click()
    page.get_by_role('button',name='保存客户',exact=True).click()
    expect(page.get_by_role('dialog')).to_be_visible()
    page.get_by_label('客户名称',exact=True).fill('测试客户')
    page.get_by_role('button',name='保存客户',exact=True).click()
    expect(page.get_by_text('共 5 位客户')).to_be_visible()
    page.get_by_role('button',name='试试添加状态筛选',exact=True).click()
    page.get_by_role('button',name='发送修改要求',exact=True).click()
    expect(page.get_by_label('客户状态',exact=True)).to_be_visible()
    page.get_by_label('客户状态',exact=True).select_option('合作中')
    page.get_by_role('button',name='搜索',exact=True).click()
    expect(page.get_by_text('共 2 位客户')).to_be_visible()
    page.get_by_role('button',name='通过此版本',exact=True).click()
    expect(page.get_by_text('v2 已通过',exact=True)).to_be_visible()
    page.get_by_role('button',name='生成文档草稿',exact=True).click()
    expect(page.get_by_role('heading',name='客户列表优化需求')).to_be_visible()
    page.get_by_role('tab',name='原型',exact=True).click()
    page.get_by_label('修改要求',exact=True).fill('把标题改为「重点客户」')
    page.get_by_role('button',name='发送修改要求',exact=True).click()
    expect(page.get_by_role('heading',name='重点客户',exact=True)).to_be_visible()
    expect(page.get_by_text('v3 原型待确认',exact=True)).to_be_visible()
    page.get_by_role('tab',name='文档',exact=True).click()
    expect(page.get_by_text('当前候选已变化。这份文档仍对应此前确认版本，请确认新原型后重新生成。')).to_be_visible()
    page.get_by_role('tab',name='原型',exact=True).click()
    page.get_by_role('button',name='撤销 / 恢复',exact=True).click()
    page.locator('.version-row').filter(has_text='v1').get_by_role('button',name='恢复',exact=True).click()
    expect(page.get_by_role('heading',name='客户列表',exact=True)).to_be_visible()
    expect(page.get_by_label('客户状态',exact=True)).to_have_count(0)
    page.get_by_role('button',name='配置模型',exact=True).click()
    page.get_by_label('Base URL',exact=True).fill('https://api.example.com/v1')
    page.get_by_label('模型名称',exact=True).fill('demo-model')
    page.get_by_label('API token（仅演示）',exact=True).fill('demo-fail')
    page.get_by_role('button',name='模拟连接测试',exact=True).click()
    expect(page.get_by_text('模拟鉴权失败：请更换演示 token。')).to_be_visible()
    page.get_by_label('API token（仅演示）',exact=True).fill('demo-token')
    page.get_by_role('button',name='保存演示配置',exact=True).click()
    expect(page.get_by_role('button',name='demo-model · 演示',exact=True)).to_be_visible()
    page.get_by_role('button',name='创建项目',exact=True).click()
    page.get_by_label('项目名称',exact=True).fill('会员服务')
    page.get_by_role('dialog').get_by_role('button',name='创建项目',exact=True).click()
    expect(page.get_by_role('heading',name='从一个页面开始',exact=True)).to_be_visible()
    page.get_by_role('button',name='通过此版本',exact=True).is_disabled()
    page.get_by_role('button',name='理解页面并建立原型',exact=True).click()
    expect(page.get_by_text('v1 原型待确认',exact=True)).to_be_visible()
    page.get_by_label('切换项目',exact=True).select_option(label='客户管理平台')
    expect(page.get_by_text('共 5 位客户')).to_be_visible()
    page.get_by_role('button',name='选择元素',exact=True).click()
    page.locator('[data-element="筛选区域"]').click()
    expect(page.get_by_text('⌖ 已选择：筛选区域',exact=True)).to_be_visible()
    page.get_by_role('button',name='退出选择',exact=True).click()
    page.get_by_label('修改要求',exact=True).fill('调整为紧凑表格')
    page.get_by_role('button',name='发送修改要求',exact=True).click()
    page.get_by_role('button',name='取消',exact=True).click()
    expect(page.get_by_text('已取消本次演示修改，当前版本没有变化。')).to_be_visible()
    page.set_viewport_size({'width':390,'height':844})
    page.screenshot(path=str(OUT/'workbench-mobile.png'), full_page=True)
    assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth'), 'mobile horizontal overflow'
    assert not errors, errors
    browser.close()
print('PASS: prototype workflow, validation, project isolation, version invalidation, cancellation, mobile layout; no page errors')
